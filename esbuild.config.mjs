import esbuild from "esbuild";
import fs from "fs";
import process from "process";
import builtins from "builtin-modules";

// Bundled third-party code keeps its licence notice (highlight.js is BSD-3-Clause).
const hljsLicense = fs.readFileSync("node_modules/highlight.js/LICENSE", "utf8").trim();
const banner = `/*
This is a generated/bundled file.
Source: https://github.com/ (SlashCommands for Obsidian)

Includes highlight.js (https://highlightjs.org/):
${hljsLicense}
*/`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
